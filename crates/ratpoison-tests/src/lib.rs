//! Cross-crate integration, multi-monitor DPI precision, and Memory Hygiene security verification suite.
//!
//! This crate bridges `ratpoison-core`, `ratpoison-hid`, `ratpoison-a11y`, and `ratpoison-license`
//! by providing type conversion helpers across independently defined crate boundary primitives
//! (`LogicalPoint`, `LogicalRect`, `PhysicalPoint`, `MouseButton`, `ClickKind`, `SpeedTier`,
//! and `LabelBadge`).

use ratpoison_a11y as a11y;
use ratpoison_core as core_engine;
use ratpoison_hid as hid;

/// Converts a `ratpoison_core::LogicalPoint` into a `ratpoison_hid::LogicalPoint`.
#[inline]
pub const fn core_to_hid_logical_point(pt: core_engine::LogicalPoint) -> hid::LogicalPoint {
    hid::LogicalPoint::new(pt.x, pt.y)
}

/// Converts a `ratpoison_hid::LogicalPoint` into a `ratpoison_core::LogicalPoint`.
#[inline]
pub const fn hid_to_core_logical_point(pt: hid::LogicalPoint) -> core_engine::LogicalPoint {
    core_engine::LogicalPoint::new(pt.x, pt.y)
}

/// Converts a `ratpoison_core::PhysicalPoint` into a `ratpoison_hid::PhysicalPoint`.
#[inline]
pub const fn core_to_hid_physical_point(pt: core_engine::PhysicalPoint) -> hid::PhysicalPoint {
    hid::PhysicalPoint::new(pt.x, pt.y)
}

/// Converts a `ratpoison_core::LogicalRect` into a `ratpoison_a11y::LogicalRect`.
#[inline]
pub const fn core_to_a11y_rect(r: core_engine::LogicalRect) -> a11y::LogicalRect {
    a11y::LogicalRect::new(r.x, r.y, r.width, r.height)
}

/// Converts a `ratpoison_a11y::LogicalRect` into a `ratpoison_core::LogicalRect`.
#[inline]
pub const fn a11y_to_core_rect(r: a11y::LogicalRect) -> core_engine::LogicalRect {
    core_engine::LogicalRect::new(r.x, r.y, r.width, r.height)
}

/// Converts a `ratpoison_a11y::LogicalPoint` into a `ratpoison_core::LogicalPoint`.
#[inline]
pub const fn a11y_to_core_point(pt: a11y::LogicalPoint) -> core_engine::LogicalPoint {
    core_engine::LogicalPoint::new(pt.x, pt.y)
}

/// Bridges an accessibility badge generated by `ratpoison-a11y` into a `ratpoison_core::LabelBadge`
/// ready for `EngineEvent::AccessibilityLabelsLoaded`.
pub fn bridge_a11y_badge_to_core(badge: &a11y::LabelBadge, monitor_id: &str) -> core_engine::LabelBadge {
    core_engine::LabelBadge {
        id: badge.element.id.clone(),
        label: badge.hint.clone(),
        title: badge
            .element
            .title
            .clone()
            .unwrap_or_else(|| badge.element.id.clone()),
        role: format!("{:?}", badge.element.role),
        rect: a11y_to_core_rect(badge.bounds),
        center: a11y_to_core_point(badge.target),
        monitor_id: monitor_id.to_string(),
    }
}

/// Maps a `ratpoison_core::MouseButton` to `ratpoison_hid::MouseButton`.
#[inline]
pub const fn core_to_hid_mouse_button(btn: core_engine::MouseButton) -> hid::MouseButton {
    match btn {
        core_engine::MouseButton::Left => hid::MouseButton::Left,
        core_engine::MouseButton::Right => hid::MouseButton::Right,
        core_engine::MouseButton::Middle => hid::MouseButton::Middle,
    }
}

/// Maps a `ratpoison_hid::ClickKind` to `ratpoison_core::MouseActionKind`.
#[inline]
pub const fn hid_click_to_core_action(kind: hid::ClickKind) -> core_engine::MouseActionKind {
    match kind {
        hid::ClickKind::Left => core_engine::MouseActionKind::LeftClick,
        hid::ClickKind::Right => core_engine::MouseActionKind::RightClick,
        hid::ClickKind::DoubleLeft => core_engine::MouseActionKind::DoubleClick,
        hid::ClickKind::Middle => core_engine::MouseActionKind::MiddleClick,
        hid::ClickKind::DragStart => core_engine::MouseActionKind::DragStart,
        hid::ClickKind::DragEnd => core_engine::MouseActionKind::DragEnd,
    }
}

/// Maps a `ratpoison_hid::SpeedTier` to `ratpoison_core::FreeKey` speed modifier key.
#[inline]
pub const fn hid_speed_to_core_free_key(tier: hid::SpeedTier) -> core_engine::FreeKey {
    match tier {
        hid::SpeedTier::Slow => core_engine::FreeKey::SpeedSlow,
        hid::SpeedTier::Normal => core_engine::FreeKey::SpeedNormal,
        hid::SpeedTier::Fast => core_engine::FreeKey::SpeedFast,
        hid::SpeedTier::Turbo => core_engine::FreeKey::SpeedTurbo,
    }
}
