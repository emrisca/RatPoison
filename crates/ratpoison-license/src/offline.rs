//! Offline / Air-Gapped Ed25519 Challenge-Response Activation Protocol.
//!
//! Flow:
//! 1. Air-gapped client calls [`generate_offline_challenge`] with `(license_key, machine_fingerprint, timestamp)`
//!    to produce a compact Base64URL challenge string prefixed with `RP-CHALLENGE-V1:`.
//! 2. User carries the challenge string (via QR code, USB key, or manual copy) to an online portal.
//! 3. License server validates the challenge and calls [`issue_offline_activation_token`] with its
//!    Ed25519 `SigningKey`, producing `RP-ACTIVATE-V1:<base64url(claims_json)>.<base64url(ed25519_sig)>`
//!    bound to `(license_key_hash, machine_fingerprint, seat_id, issued_at, expires_at)`.
//! 4. Air-gapped client calls [`verify_offline_activation_token`] (or `LicenseManager::apply_offline_response`)
//!    to verify the Ed25519 signature offline, enforce machine-fingerprint binding, and atomically persist the seat.

use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine as _};
use ed25519_dalek::{Signature, Signer, SigningKey, Verifier, VerifyingKey};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use zeroize::Zeroizing;

use crate::error::LicenseError;
use crate::fingerprint::{hex_encode, normalize_and_hash_license_key};
use crate::manager::MAX_MACHINES;

/// Wire prefix for offline challenge strings generated by air-gapped clients.
pub const OFFLINE_CHALLENGE_PREFIX: &str = "RP-CHALLENGE-V1:";

/// Wire prefix for offline signed activation tokens issued by the licensing authority.
pub const OFFLINE_TOKEN_PREFIX: &str = "RP-ACTIVATE-V1:";

/// Structured payload encoded inside an offline challenge code.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OfflineChallengePayload {
    /// Protocol schema version (`1`).
    pub version: u8,
    /// Salted SHA-256 hash of the user's normalized license key.
    pub license_key_hash: String,
    /// Salted SHA-256 hardware fingerprint of the air-gapped machine.
    pub machine_fingerprint: String,
    /// Friendly hostname for seat registry display.
    pub friendly_hostname: String,
    /// Platform identifier (`macos`, `windows`, `linux`).
    pub os: String,
    /// Unix epoch timestamp (seconds) when the challenge was generated.
    pub timestamp: u64,
    /// Deterministic 128-bit hex challenge nonce binding the request tuple.
    pub nonce: String,
}

/// Signed claims embedded inside an offline activation response token.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OfflineActivationClaims {
    /// Protocol schema version (`1`).
    pub version: u8,
    /// Salted SHA-256 hash of the license key.
    pub license_key_hash: String,
    /// Target machine's SHA-256 fingerprint that this token is cryptographically bound to.
    pub machine_fingerprint: String,
    /// Assigned seat number (`1..=5`).
    pub seat_id: u8,
    /// Unix epoch timestamp (seconds) when the activation token was signed.
    pub issued_at: u64,
    /// Optional expiration Unix timestamp (`None` for perpetual major-version license).
    pub expires_at: Option<u64>,
    /// Echoed challenge nonce to prevent cross-challenge replay.
    pub challenge_nonce: String,
}

/// Generates a compact Base64URL offline challenge code for air-gapped activation.
///
/// The raw `license_key` is immediately moved into a `Zeroizing<String>` guard during hashing
/// and never appears in plaintext inside the challenge code.
pub fn generate_offline_challenge(
    license_key: &str,
    machine_fingerprint: &str,
    timestamp: u64,
) -> Result<String, LicenseError> {
    generate_offline_challenge_with_metadata(
        license_key,
        machine_fingerprint,
        timestamp,
        "airgapped-workstation",
        std::env::consts::OS,
    )
}

/// Generates an offline challenge code including explicit hostname and OS metadata.
pub fn generate_offline_challenge_with_metadata(
    license_key: &str,
    machine_fingerprint: &str,
    timestamp: u64,
    friendly_hostname: &str,
    os: &str,
) -> Result<String, LicenseError> {
    let key_guard = Zeroizing::new(license_key.to_string());
    let license_key_hash = normalize_and_hash_license_key(key_guard.as_str())?;

    let fp_trimmed = machine_fingerprint.trim();
    if fp_trimmed.is_empty() {
        return Err(LicenseError::MalformedChallenge(
            "machine_fingerprint cannot be empty".to_string(),
        ));
    }

    // Derive a 16-byte nonce from (license_key_hash || machine_fingerprint || timestamp)
    let mut nonce_hasher = Sha256::new();
    nonce_hasher.update(b"ratpoison.offline-challenge.nonce.v1:");
    nonce_hasher.update(license_key_hash.as_bytes());
    nonce_hasher.update(b":");
    nonce_hasher.update(fp_trimmed.as_bytes());
    nonce_hasher.update(b":");
    nonce_hasher.update(timestamp.to_be_bytes());
    let full_nonce = nonce_hasher.finalize();
    let nonce = hex_encode(&full_nonce[..16]);

    let payload = OfflineChallengePayload {
        version: 1,
        license_key_hash,
        machine_fingerprint: fp_trimmed.to_string(),
        friendly_hostname: friendly_hostname.trim().to_string(),
        os: os.trim().to_string(),
        timestamp,
        nonce,
    };

    let json_bytes = serde_json::to_vec(&payload)
        .map_err(|e| LicenseError::Serialization(e.to_string()))?;
    let encoded = URL_SAFE_NO_PAD.encode(&json_bytes);
    Ok(format!("{OFFLINE_CHALLENGE_PREFIX}{encoded}"))
}

/// Decodes and validates an offline challenge string produced by [`generate_offline_challenge`].
pub fn decode_offline_challenge(
    challenge_code: &str,
) -> Result<OfflineChallengePayload, LicenseError> {
    let trimmed = challenge_code.trim();
    let b64_part = trimmed
        .strip_prefix(OFFLINE_CHALLENGE_PREFIX)
        .ok_or_else(|| {
            LicenseError::MalformedChallenge(format!(
                "missing required prefix '{OFFLINE_CHALLENGE_PREFIX}'"
            ))
        })?;

    let raw_bytes = URL_SAFE_NO_PAD
        .decode(b64_part)
        .map_err(|e| LicenseError::MalformedChallenge(format!("invalid base64url: {e}")))?;

    let payload: OfflineChallengePayload = serde_json::from_slice(&raw_bytes)
        .map_err(|e| LicenseError::MalformedChallenge(format!("invalid challenge JSON: {e}")))?;

    if payload.version != 1 {
        return Err(LicenseError::MalformedChallenge(format!(
            "unsupported challenge version {}",
            payload.version
        )));
    }
    if payload.machine_fingerprint.is_empty() || payload.license_key_hash.is_empty() {
        return Err(LicenseError::MalformedChallenge(
            "challenge missing required fingerprint or license key hash".to_string(),
        ));
    }

    Ok(payload)
}

/// Server/issuer-side helper that validates a client challenge code and signs an Ed25519
/// activation token bound to `(license_key_hash, machine_fingerprint, seat_id, issued_at, expires_at)`.
pub fn issue_offline_activation_token(
    signing_key: &SigningKey,
    challenge_code: &str,
    expected_license_key: &str,
    seat_id: u8,
    issued_at: u64,
    expires_at: Option<u64>,
) -> Result<String, LicenseError> {
    if seat_id == 0 || (seat_id as usize) > MAX_MACHINES {
        return Err(LicenseError::InvalidSeatId(seat_id));
    }

    let challenge = decode_offline_challenge(challenge_code)?;
    let expected_key_guard = Zeroizing::new(expected_license_key.to_string());
    let expected_key_hash = normalize_and_hash_license_key(expected_key_guard.as_str())?;

    if challenge.license_key_hash != expected_key_hash {
        return Err(LicenseError::LicenseKeyMismatch);
    }

    let claims = OfflineActivationClaims {
        version: 1,
        license_key_hash: challenge.license_key_hash,
        machine_fingerprint: challenge.machine_fingerprint,
        seat_id,
        issued_at,
        expires_at,
        challenge_nonce: challenge.nonce,
    };

    sign_offline_claims(signing_key, &claims)
}

/// Low-level helper to sign an [`OfflineActivationClaims`] structure with an Ed25519 `SigningKey`.
pub fn sign_offline_claims(
    signing_key: &SigningKey,
    claims: &OfflineActivationClaims,
) -> Result<String, LicenseError> {
    if claims.seat_id == 0 || (claims.seat_id as usize) > MAX_MACHINES {
        return Err(LicenseError::InvalidSeatId(claims.seat_id));
    }

    let claims_json = serde_json::to_vec(claims)
        .map_err(|e| LicenseError::Serialization(e.to_string()))?;
    let claims_b64 = URL_SAFE_NO_PAD.encode(&claims_json);

    // Sign the exact UTF-8 bytes of the base64url-encoded claims payload
    let signature: Signature = signing_key.sign(claims_b64.as_bytes());
    let sig_b64 = URL_SAFE_NO_PAD.encode(signature.to_bytes());

    Ok(format!("{OFFLINE_TOKEN_PREFIX}{claims_b64}.{sig_b64}"))
}

/// Verifies an offline activation token's Ed25519 signature, machine fingerprint binding,
/// seat bounds, and optional expiration timestamp.
pub fn verify_offline_activation_token(
    token: &str,
    verifying_key: &VerifyingKey,
    expected_machine_fingerprint: &str,
    current_timestamp: u64,
) -> Result<OfflineActivationClaims, LicenseError> {
    let trimmed = token.trim();
    let body = trimmed
        .strip_prefix(OFFLINE_TOKEN_PREFIX)
        .ok_or_else(|| {
            LicenseError::MalformedActivationToken(format!(
                "missing required prefix '{OFFLINE_TOKEN_PREFIX}'"
            ))
        })?;

    let (claims_b64, sig_b64) = body.split_once('.').ok_or_else(|| {
        LicenseError::MalformedActivationToken(
            "expected '<claims_b64>.<signature_b64>' structure".to_string(),
        )
    })?;

    let sig_bytes = URL_SAFE_NO_PAD.decode(sig_b64).map_err(|e| {
        LicenseError::MalformedActivationToken(format!("invalid signature base64url: {e}"))
    })?;

    let signature = Signature::from_slice(&sig_bytes).map_err(|_| {
        LicenseError::MalformedActivationToken(
            "Ed25519 signature must be exactly 64 bytes".to_string(),
        )
    })?;

    // Verify Ed25519 signature over the exact claims_b64 ASCII payload
    verifying_key
        .verify(claims_b64.as_bytes(), &signature)
        .map_err(|_| LicenseError::SignatureVerificationFailed)?;

    let claims_json = URL_SAFE_NO_PAD.decode(claims_b64).map_err(|e| {
        LicenseError::MalformedActivationToken(format!("invalid claims base64url: {e}"))
    })?;

    let claims: OfflineActivationClaims = serde_json::from_slice(&claims_json).map_err(|e| {
        LicenseError::MalformedActivationToken(format!("invalid claims JSON: {e}"))
    })?;

    if claims.version != 1 {
        return Err(LicenseError::MalformedActivationToken(format!(
            "unsupported token version {}",
            claims.version
        )));
    }

    if claims.seat_id == 0 || (claims.seat_id as usize) > MAX_MACHINES {
        return Err(LicenseError::InvalidSeatId(claims.seat_id));
    }

    if claims.machine_fingerprint != expected_machine_fingerprint.trim() {
        return Err(LicenseError::FingerprintMismatch {
            expected: expected_machine_fingerprint.trim().to_string(),
            actual: claims.machine_fingerprint,
        });
    }

    if let Some(exp) = claims.expires_at {
        if current_timestamp > exp {
            return Err(LicenseError::TokenExpired {
                expires_at: exp,
                current: current_timestamp,
            });
        }
    }

    Ok(claims)
}
